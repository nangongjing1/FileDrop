#!/usr/bin/env python3
"""Embed web/ assets into a generated C++ source file."""

from __future__ import annotations

import pathlib
import sys

MIME_BY_SUFFIX = {
    ".html": "text/html; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".js": "application/javascript; charset=utf-8",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".json": "application/json; charset=utf-8",
}

PATH_BY_NAME = {
    "index.html": "/",
    "admin.html": "/admin",
}

DELIMITER = ")FDWEB"


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: embed_web.py <web-dir> <output.cpp>", file=sys.stderr)
        return 2

    web_dir = pathlib.Path(sys.argv[1])
    output = pathlib.Path(sys.argv[2])
    if not web_dir.is_dir():
        print(f"web directory not found: {web_dir}", file=sys.stderr)
        return 1

    entries = []
    for path in sorted(web_dir.iterdir()):
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8")
        if DELIMITER + '"' in text:
            print(f"asset contains raw-string delimiter: {path}", file=sys.stderr)
            return 1
        key = PATH_BY_NAME.get(path.name, "/" + path.name)
        mime = MIME_BY_SUFFIX.get(path.suffix, "application/octet-stream")
        entries.append((key, mime, text))

    if not any(key == "/" for key, _, _ in entries):
        print("index.html is required", file=sys.stderr)
        return 1

    lines = [
        "// Generated by tools/embed_web.py. Do not edit by hand.",
        '#include "web_assets.h"',
        "",
        "namespace {",
        "",
    ]
    for index, (_, _, text) in enumerate(entries):
        lines.append(f"const char kAsset{index}[] = R\"FDWEB({text})FDWEB\";")
        lines.append("")
    lines.append("}  // namespace")
    lines.append("")
    lines.append("const std::unordered_map<std::string, WebAsset>& webAssets() {")
    lines.append("  static const std::unordered_map<std::string, WebAsset> assets = {")
    for index, (key, mime, _) in enumerate(entries):
        lines.append(
            f'      {{"{key}", {{"{mime}", kAsset{index}, sizeof(kAsset{index}) - 1}}}},'
        )
    lines.append("  };")
    lines.append("  return assets;")
    lines.append("}")
    lines.append("")

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"embedded {len(entries)} assets -> {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
